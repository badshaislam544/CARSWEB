// Translate vehicle condition labels
Garirbazar.conditionLabel = (cond) => {
  if (cond === 'Reconditioned') return Garirbazar.t('reconditioned');
  if (cond === 'New') return Garirbazar.t('brandNew');
  return Garirbazar.t('used');
};